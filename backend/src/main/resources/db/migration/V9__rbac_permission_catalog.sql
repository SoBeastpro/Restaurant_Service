CREATE OR REPLACE VIEW identity.effective_platform_permissions AS
SELECT user_role.user_id, role_permission.permission_code
FROM identity.user_platform_roles user_role
JOIN identity.platform_role_permissions role_permission
  ON role_permission.role_code = user_role.role_code
JOIN identity.users user_row ON user_row.id = user_role.user_id
WHERE user_row.status = 'ACTIVE';

